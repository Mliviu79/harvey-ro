// ── Dashboard language: Romanian by default, English on request ──
//
// t(key, vars) looks the key up in the current language (Romanian unless
// this browser chose English), falls back to English, then to the key
// itself. A value can be {one, few, other}: the form is picked by
// Intl.PluralRules for vars.n. {name} placeholders take vars as given:
// callers escape API data before it goes into HTML, and numbers are
// formatted for the language (1.234 / 1,234).
//
// Server text the dashboard shows (signal descriptions, provider notes) is
// translated by stable key only while the server's English still equals
// the English stored here (tServer in app.js), so a translation never goes
// stale silently.
//
// No DOM work happens when this file loads: applyI18n() does it, so the
// file also runs under node for the tests.

const I18N_LANGS = ['ro', 'en'];
const I18N_KEY = 'harvey-lang';

let LANG = (function () {
  try { return localStorage.getItem(I18N_KEY) === 'en' ? 'en' : 'ro'; } catch (e) { return 'ro'; }
})();

function getLang() { return LANG; }

function intlLocale(lang) { return (lang || LANG) === 'en' ? 'en-GB' : 'ro-RO'; }

function fmtN(n, lang) {
  try { return new Intl.NumberFormat(intlLocale(lang)).format(n); } catch (e) { return String(n); }
}

// Dollar amounts (provider prices are in USD) the way the language writes
// money: "0,25 $" in Romanian, "$0.25" in English.
function fmtUsd(n, digits, lang) {
  const d = digits === undefined ? 2 : digits;
  try {
    return new Intl.NumberFormat(intlLocale(lang), {style: 'currency', currency: 'USD', currencyDisplay: 'narrowSymbol',
      minimumFractionDigits: d, maximumFractionDigits: d}).format(Number(n) || 0);
  } catch (e) { return '$' + (Number(n) || 0).toFixed(d); }
}

function hasKey(lang, key) {
  return Object.prototype.hasOwnProperty.call(I18N[lang] || {}, key);
}

function t(key, vars, lang) {
  const L = lang || LANG;
  let v = hasKey(L, key) ? I18N[L][key] : hasKey('en', key) ? I18N.en[key] : undefined;
  if (v === undefined) return key;
  if (typeof v === 'object') {
    const n = Number(vars && vars.n) || 0;
    let form = 'other';
    try { form = new Intl.PluralRules(intlLocale(L)).select(n); } catch (e) { form = n === 1 ? 'one' : 'other'; }
    v = v[form] !== undefined ? v[form] : v.other;
  }
  return String(v).replace(/\{(\w+)\}/g, (m, k) => {
    if (!vars || !Object.prototype.hasOwnProperty.call(vars, k)) return m;
    const x = vars[k];
    return typeof x === 'number' ? fmtN(x, L) : String(x === null || x === undefined ? '' : x);
  });
}

// Static text in index.html. data-i18n-html is for this file's own strings
// only (never API data), so it may carry <b>, <code> and links.
function applyI18n(root) {
  if (typeof document === 'undefined' || !document.querySelectorAll) return;
  const scope = root || document;
  scope.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  scope.querySelectorAll('[data-i18n-html]').forEach(el => { el.innerHTML = t(el.dataset.i18nHtml); });
  scope.querySelectorAll('[data-i18n-placeholder]').forEach(el => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  scope.querySelectorAll('[data-i18n-title]').forEach(el => { el.title = t(el.dataset.i18nTitle); });
  scope.querySelectorAll('[data-i18n-aria]').forEach(el => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
  document.documentElement.lang = LANG;
  document.title = t('doc.title');
}

function setLang(lang) {
  LANG = I18N_LANGS.includes(lang) ? lang : 'ro';
  try { localStorage.setItem(I18N_KEY, LANG); } catch (e) { /* private mode */ }
  applyI18n();
}

